-- =====================================================================================================
-- Health Centre RFID record system - PostgreSQL schema
-- Holds identity data only. Visits live in MongoDB (db/mongo/init.js).
-- Needs PostgreSQL 13+ (gen_random_uuid() is built in) and the pg_trgm extension (ships with the
-- official postgres image). Safe to run twice.
-- Style: SQL keywords and functions UPPERCASE, identifiers lowercase.
-- =====================================================================================================

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ---- reference data ---------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS branch (
    branch_id    SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code  TEXT NOT NULL UNIQUE,
    branch_name  TEXT NOT NULL UNIQUE
);

