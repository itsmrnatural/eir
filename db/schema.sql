-- Explicit ids above do not advance an identity sequence. Start generated ids at 100 so they never
-- collide with the seeded rows; safe to run again (never moves the sequence backwards).
SELECT setval(pg_get_serial_sequence('branch', 'branch_id'),
              GREATEST((SELECT COALESCE(MAX(branch_id), 99) FROM branch), 99), true);

-- ---- patients (supertype) and the two subtypes ------------------------------------------------------
CREATE TABLE IF NOT EXISTS patient (
    patient_id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name                 TEXT NOT NULL,
    dob                  DATE NULL,
    age_at_registration  SMALLINT NULL,
    registered_on        DATE NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Kolkata')::DATE,
    sex                  TEXT NOT NULL CHECK (sex IN ('M', 'F', 'Other')),
    patient_type         TEXT NOT NULL CHECK (patient_type IN ('STUDENT', 'NON_STUDENT')),
    created_at           TIMESTAMPTZ DEFAULT NOW(),
    updated_at           TIMESTAMPTZ DEFAULT NOW(),
    CHECK ( (patient_type = 'STUDENT' AND dob IS NOT NULL)
         OR (patient_type = 'NON_STUDENT' AND age_at_registration BETWEEN 0 AND 120) ),
    -- Addition to the CHECK above evaluates to NULL (= passes) when a NON_STUDENT has no
    -- age_at_registration, so it must be required explicitly.
    CONSTRAINT patient_non_student_age_required
        CHECK (patient_type <> 'NON_STUDENT' OR age_at_registration IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS student (
    patient_id  UUID PRIMARY KEY REFERENCES patient (patient_id),
    roll_no     TEXT NOT NULL,
    batch_year  SMALLINT NOT NULL,                       -- admission year, 4 digits, e.g. 2025
    program     TEXT NOT NULL CHECK (program IN ('UG', 'PG')),
    branch_id   SMALLINT NOT NULL,
    CONSTRAINT student_roll_no_key UNIQUE (roll_no),
    CONSTRAINT student_branch_id_fkey FOREIGN KEY (branch_id) REFERENCES branch (branch_id)
);

CREATE TABLE IF NOT EXISTS non_student (
    patient_id   UUID PRIMARY KEY REFERENCES patient (patient_id),
    phone_no     TEXT NOT NULL,
    designation  TEXT NOT NULL CHECK (designation IN ('STAFF', 'FACULTY', 'WORKER', 'OTHER'))
);

CREATE TABLE IF NOT EXISTS student_rfid (
    rfid_id    TEXT PRIMARY KEY,
    roll_no    TEXT NOT NULL REFERENCES student (roll_no),
    is_active  BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS users (
    user_id        SERIAL PRIMARY KEY,
    username       TEXT NOT NULL,
    password_hash  TEXT NOT NULL,
    role           TEXT NOT NULL CHECK (role IN ('ADMIN', 'STAFF')),
    CONSTRAINT users_username_key UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS audit_log (
    audit_id       BIGSERIAL PRIMARY KEY,
    actor_user_id  INT REFERENCES users (user_id),       -- NULL for command-line scripts
    entity         TEXT,
    entity_id      TEXT,
    action         TEXT,
    before         JSONB,
    after          JSONB,
    at             TIMESTAMPTZ DEFAULT NOW()
);

-- ---- indexes ----------------------------------------------------------------------------------------
-- RFID tap: student_rfid_pkey (rfid_id) answers the lookup; roll_no is then a unique-index probe on student.
CREATE INDEX        IF NOT EXISTS student_rfid_roll_no_idx    ON student_rfid (roll_no);
-- at most one ACTIVE tag per student
CREATE UNIQUE INDEX IF NOT EXISTS student_rfid_one_active     ON student_rfid (roll_no) WHERE is_active;
CREATE INDEX        IF NOT EXISTS student_branch_id_idx       ON student (branch_id);
CREATE INDEX        IF NOT EXISTS non_student_phone_no_idx    ON non_student (phone_no);
-- partial-match search (name / roll_no / phone) with LIKE '%text%'
CREATE INDEX IF NOT EXISTS patient_name_trgm_idx       ON patient     USING GIN (LOWER(name)    gin_trgm_ops);
CREATE INDEX IF NOT EXISTS student_roll_no_trgm_idx    ON student     USING GIN (LOWER(roll_no) gin_trgm_ops);
CREATE INDEX IF NOT EXISTS non_student_phone_trgm_idx  ON non_student USING GIN (phone_no       gin_trgm_ops);
CREATE INDEX IF NOT EXISTS audit_log_entity_idx        ON audit_log (entity, entity_id, at DESC);

-- ---- triggers ---------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS patient_touch_updated_at ON patient;
CREATE TRIGGER patient_touch_updated_at BEFORE UPDATE ON patient
    FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

-- A student row must belong to a STUDENT patient and a non_student row to a NON_STUDENT patient.
CREATE OR REPLACE FUNCTION check_subtype_matches_patient() RETURNS TRIGGER AS $$
DECLARE
    expected TEXT := CASE TG_TABLE_NAME WHEN 'student' THEN 'STUDENT' ELSE 'NON_STUDENT' END;
BEGIN
    IF (SELECT p.patient_type FROM patient p WHERE p.patient_id = NEW.patient_id) IS DISTINCT FROM expected THEN
        RAISE EXCEPTION 'patient % is not a % patient', NEW.patient_id, expected USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS student_subtype_check ON student;
CREATE TRIGGER student_subtype_check BEFORE INSERT OR UPDATE ON student
    FOR EACH ROW EXECUTE FUNCTION check_subtype_matches_patient();
DROP TRIGGER IF EXISTS non_student_subtype_check ON non_student;
CREATE TRIGGER non_student_subtype_check BEFORE INSERT OR UPDATE ON non_student
    FOR EACH ROW EXECUTE FUNCTION check_subtype_matches_patient();

-- ... and every patient must end up with its subtype row (checked at COMMIT, so both inserts can happen in one transaction).
CREATE OR REPLACE FUNCTION check_patient_has_subtype() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.patient_type = 'STUDENT' AND NOT EXISTS (SELECT 1 FROM student s WHERE s.patient_id = NEW.patient_id) THEN
        RAISE EXCEPTION 'student patient % has no student row', NEW.patient_id USING ERRCODE = '23514';
    END IF;
    IF NEW.patient_type = 'NON_STUDENT' AND NOT EXISTS (SELECT 1 FROM non_student n WHERE n.patient_id = NEW.patient_id) THEN
        RAISE EXCEPTION 'non-student patient % has no non_student row', NEW.patient_id USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS patient_has_subtype ON patient;
CREATE CONSTRAINT TRIGGER patient_has_subtype AFTER INSERT ON patient
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_patient_has_subtype();

-- Phone rules: (phone_no, lower(name)) is unique and a phone has at most 5 patients.
-- The name lives in `patient` and the phone in `non_student`, so a UNIQUE index cannot express this:
-- it is a trigger. Deferred to COMMIT so a patch that changes name and phone together is judged on
-- the final state. The advisory lock serialises concurrent commits for the same phone number.
-- Custom SQLSTATEs: HC001 = PHONE_LIMIT_REACHED, HC002 = DUPLICATE_PATIENT (mapped in pg-helpers.js).
CREATE OR REPLACE FUNCTION enforce_phone_rules() RETURNS TRIGGER AS $$
DECLARE
    the_phone  TEXT;
    the_id     UUID;
    the_name   TEXT;
BEGIN
    IF TG_TABLE_NAME = 'non_student' THEN
        the_phone := NEW.phone_no;
        the_id    := NEW.patient_id;
    ELSE  -- fired by a name change on patient
        SELECT n.phone_no INTO the_phone FROM non_student n WHERE n.patient_id = NEW.patient_id;
        IF the_phone IS NULL THEN
            RETURN NULL;       -- a student: no phone rules
        END IF;
        the_id := NEW.patient_id;
    END IF;

    PERFORM pg_advisory_xact_lock(HASHTEXT('phone:' || the_phone));
    SELECT p.name INTO the_name FROM patient p WHERE p.patient_id = the_id;

    IF EXISTS (SELECT 1
                 FROM non_student n JOIN patient p ON p.patient_id = n.patient_id
                WHERE n.phone_no = the_phone AND n.patient_id <> the_id AND LOWER(p.name) = LOWER(the_name)) THEN
        RAISE EXCEPTION 'phone % already has a patient named %', the_phone, the_name USING ERRCODE = 'HC002';
    END IF;

    IF (SELECT COUNT(*) FROM non_student n WHERE n.phone_no = the_phone AND n.patient_id <> the_id) >= 5 THEN
        RAISE EXCEPTION 'phone % already has 5 registered patients', the_phone USING ERRCODE = 'HC001';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS non_student_phone_rules ON non_student;
CREATE CONSTRAINT TRIGGER non_student_phone_rules AFTER INSERT OR UPDATE ON non_student
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION enforce_phone_rules();
DROP TRIGGER IF EXISTS patient_name_phone_rules ON patient;
CREATE CONSTRAINT TRIGGER patient_name_phone_rules AFTER UPDATE OF name ON patient
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION enforce_phone_rules();

-- ---- view: PatientView source (age is computed, never stored) -------------------------------------
-- "today" is the Asia/Kolkata calendar day. AGE() counts full years, like a birthday.
--   students     : age = full years since dob
--   non-students : age = age_at_registration + full years since registered_on   (age_is_estimated = TRUE)
-- rfid_id is the student's ACTIVE tag (if any).
CREATE OR REPLACE VIEW patient_with_age AS
SELECT p.patient_id,
       p.patient_type,
       p.name,
       p.sex,
       p.dob,
       p.age_at_registration,
       p.registered_on,
       CASE p.patient_type
            WHEN 'STUDENT' THEN DATE_PART('year', AGE(t.today, p.dob))::INT
            ELSE p.age_at_registration + DATE_PART('year', AGE(t.today, p.registered_on))::INT
       END AS age,
       (p.patient_type = 'NON_STUDENT') AS age_is_estimated,
       s.roll_no,
       s.batch_year,
       s.program,
       s.branch_id,
       b.branch_code,
       b.branch_name,
       n.phone_no,
       n.designation,
       r.rfid_id
  FROM patient p
 CROSS JOIN (SELECT (NOW() AT TIME ZONE 'Asia/Kolkata')::DATE AS today) t
  LEFT JOIN student s      ON s.patient_id = p.patient_id
  LEFT JOIN branch b       ON b.branch_id = s.branch_id
  LEFT JOIN non_student n  ON n.patient_id = p.patient_id
  LEFT JOIN student_rfid r ON r.roll_no = s.roll_no AND r.is_active;

COMMENT ON VIEW patient_with_age IS 'PatientView source: patient + subtype + branch + active RFID, with age computed in Asia/Kolkata.';
COMMENT ON TABLE audit_log IS 'Before/after JSON of every patient edit, visit edit and RFID relink. actor_user_id is NULL for CLI scripts.';
